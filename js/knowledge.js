  /** 根据名称/子类/产区关键词推断风味标签 */
  SA.inferFlavor = function (text, category) {
    var t = String(text || '').toLowerCase();
    var out = [];
    SA.FLAVOR_RULES.forEach(function (rule) {
      for (var i = 0; i < rule.keys.length; i++) {
        if (t.indexOf(rule.keys[i]) !== -1) {
          rule.tags.forEach(function (tag) { if (out.indexOf(tag) === -1 && out.length < 5) out.push(tag); });
          return;
        }
      }
    });
    if (!out.length) {
      var fallback = {
        red: ['红色浆果', '单宁', '橡木'], white: ['柑橘', '白花', '清爽'],
        sparkling: ['气泡', '柑橘', '酵母'], whisky: ['橡木', '麦芽', '辛香'],
        beer: ['麦芽', '酒花', '清爽'], cocktail: ['酸甜', '果香', '冰凉'],
        fortified: ['干果', '坚果', '焦糖']
      };
      out = fallback[category] || ['待品鉴'];
    }
    return out;
  };

  /** 陈年潜力评分（0–1），用于地球上的「年份光圈」粗细 */
  SA.agingScore = function (item) {
    var base = { red: 0.55, white: 0.3, sparkling: 0.45, whisky: 0.8, beer: 0.12, cocktail: 0.05, fortified: 0.85 }[item.category] || 0.3;
    if (item.age) base = Math.min(0.98, base + item.age / 30);
    if (item.rating) base += (item.rating - 4.2) * 0.15;
    return Math.max(0.08, Math.min(0.98, base));
  };

